import assert from 'node:assert/strict';
import {consoleGraph} from '../scripts/apps/console-graph.mjs';
import {overviewTokens,overviewMove,escapeOverview} from '../scripts/apps/console-overview.mjs';
import {zapAnchors,selfAnchor} from '../scripts/apps/console-effects.mjs';
const canvas={archId:'a',floors:[{index:0,floorId:'f0',participants:[{ref:'runner:p',pid:'p',name:'Runner',img:'portrait.png',isMine:true}],entities:[{ref:'ice:a:f0:i',name:'ICE',gmDraggable:true},{ref:'demon:a:f0:d',name:'Demon',isDemon:true,gmDraggable:true},{ref:'prog:p:bi',name:'Program',isProgram:true,gmDraggable:true}]},{index:1,floorId:'f1',kind:'file'},{index:2,floorId:'f2',encrypted:true,entities:[{ref:'ice:SECRET',name:'SECRET',gmDraggable:true}],participants:[{ref:'runner:SECRET',name:'SECRET',isMine:true}]}]};
const graph=consoleGraph(canvas);
assert.equal(graph.nodes[0].tokens.length,4,'every participant, ICE, demon and program appears');
assert.deepEqual(graph.nodes[0].tokens.map(t=>t.ref),['runner:p','ice:a:f0:i','demon:a:f0:d','prog:p:bi']);
assert.equal(graph.nodes[0].tokens[0].img,'portrait.png');
assert.equal(graph.nodes[1].isFile,true);
assert.ok(!JSON.stringify(graph).includes('SECRET'));
assert.ok(!JSON.stringify(overviewTokens(canvas)).includes('SECRET'));
assert.deepEqual(overviewMove(canvas,'runner:p',1),{op:'session.move',payload:{pid:'p',floorIndex:1}});
assert.deepEqual(overviewMove(canvas,'runner:p',1,{placement:true}),{op:'session.reposition',payload:{pid:'p',floorIndex:1}});
assert.deepEqual(overviewMove(canvas,'ice:a:f0:i',1),{op:'ent.move',payload:{archId:'a',entId:'i',toFloorIndex:1}});
assert.deepEqual(overviewMove(canvas,'demon:a:f0:d',1),{op:'ent.move',payload:{archId:'a',entId:'d',toFloorIndex:1}});
assert.deepEqual(overviewMove(canvas,'prog:p:bi',1),{op:'run.progFloor',payload:{pid:'p',programId:'bi',floorIndex:1}});
assert.equal(overviewMove(canvas,'runner:p',0),null,'same floor is a no-op');
assert.equal(overviewMove(canvas,'runner:p',99),null,'unseen destinations are not available');
assert.equal(overviewMove(canvas,'ice:SECRET',1),null,'encrypted entities cannot be moved through this UI');
const player=structuredClone(canvas);player.floors[0].entities.forEach(e=>e.gmDraggable=false);
assert.equal(overviewMove(player,'ice:a:f0:i',1),null,'player cannot move the GM ICE');
assert.ok(overviewMove(player,'runner:p',2),'a sensed floor can be approached; authoritative server checks adjacency/password');
const many=structuredClone(canvas);many.floors[0].participants.push(...Array.from({length:12},(_,i)=>({ref:`runner:${i}`})));
assert.equal(consoleGraph(many).nodes[0].tokens.length,16,'no arbitrary slice silently hides tokens');
assert.equal(escapeOverview('<img src="x" onerror=\'bad\'>'),'&lt;img src=&quot;x&quot; onerror=&#39;bad&#39;&gt;');

globalThis.getComputedStyle=()=>({overflowX:'visible',overflowY:'visible'});
const rect=(left,top,width,height)=>({left,top,width,height,right:left+width,bottom:top+height});
let targetRect=rect(440,250,48,48);
const image=r=>({getClientRects:()=>[1],getBoundingClientRect:r});
const source=image(()=>rect(180,150,48,48)),target=image(()=>targetRect);
const nodes=[{dataset:{entityRef:'runner:p'},querySelector:()=>source},{dataset:{entityRef:'ice:a:f0:i'},querySelector:()=>target}];
const viewport={getClientRects:()=>[1],getBoundingClientRect:()=>rect(150,100,500,450)};
const root={querySelectorAll:()=>nodes,querySelector:()=>viewport};
const bounds=rect(100,50,800,600),refs={sourceRef:'runner:p',targetRef:'ice:a:f0:i'};
assert.deepEqual(zapAnchors(root,bounds,refs).from,{x:104,y:124});
assert.equal(selfAnchor(root,bounds,'runner:p').x,104);
assert.equal(selfAnchor(root,bounds,'runner:p').y,124);
assert.equal(selfAnchor(root,bounds,'hidden'),null,'unrendered actors cannot get self effects');
assert.deepEqual(zapAnchors(root,bounds,refs).to,{x:364,y:224});
targetRect=rect(480,280,48,48);assert.deepEqual(zapAnchors(root,bounds,refs).to,{x:404,y:254},'anchors follow moved/zoomed tokens each frame');
targetRect=rect(10,280,48,48);assert.equal(zapAnchors(root,bounds,refs),null,'offscreen target does not redirect the bolt');
assert.equal(zapAnchors(root,bounds,{...refs,targetRef:'hidden'}),null,'unrendered targets have no effect');
assert.equal(zapAnchors(root,bounds,{sourceRef:'runner:p',targetRef:'runner:p'}),null);
console.log('Overview: complete token identities, fog, move authorization/plans, file escaping, exact moving Zap anchors and offscreen suppression passed');
