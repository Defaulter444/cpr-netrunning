import assert from 'node:assert/strict';
import {consoleSnapshot,consoleChanges,appendConsoleEvents,consoleFloorSummary,CONSOLE_LOG_LIMIT} from '../scripts/apps/console-state.mjs';
const data={canvas:{archId:'a',floors:[{index:0,number:1,label:'Entry',showDv:false,dv:999},{index:1,encrypted:true,label:'SECRET',dv:42,entities:[{name:'SECRET ICE'}],markers:{breached:true}}]},actions:{variant:'runner',pid:'p',jackedIn:true,floorIndex:0,actionsValue:3,programs:[{id:'x',name:'Armor',rezzed:false}],controlNodes:[]}};
const a=consoleSnapshot(data);
assert.ok(!JSON.stringify(a).includes('SECRET'));
assert.deepEqual(consoleFloorSummary(data.canvas,1),{encrypted:true});
assert.equal(consoleFloorSummary(data.canvas,0).dv,null);
assert.equal(consoleFloorSummary({empty:true,...{floors:data.canvas.floors}},0),null);
assert.deepEqual(consoleChanges(null,a),[],'opening the window does not replay events');
assert.deepEqual(consoleChanges(a,a),[],'rerenders never duplicate events');
const updated=structuredClone(data);updated.actions.floorIndex=1;updated.actions.actionsValue=2;updated.actions.programs[0].rezzed=true;
let changes=consoleChanges(a,consoleSnapshot(updated));
assert.ok(!JSON.stringify(changes).includes('SECRET'));
assert.equal(changes.find(e=>e.key==='Moved').floor,null,'unrevealed movement has no hidden index');
updated.canvas.floors[1]={index:1,number:2,label:'Archive',markers:{breached:true}};
changes=consoleChanges(a,consoleSnapshot(updated));
assert.deepEqual(changes.map(e=>e.key),['Moved','ActionsChanged','Discovered','ProgramOn']);
assert.equal(changes[0].values.floor,'Archive');
assert.deepEqual(consoleChanges(a,{...a,scope:'b|p'}),[],'changing architecture has no false movement');
assert.deepEqual(consoleChanges(a,{...a,scope:'a|other'}),[],'changing participant has no false movement');
assert.equal(consoleChanges(a,{...a,connected:false})[0].key,'Disconnected');
assert.equal(consoleChanges({...a,connected:false},a)[0].key,'Connected');
const controlled={...a,nodes:[{id:'n',label:'Camera'}]};
assert.equal(consoleChanges(a,controlled)[0].key,'ControlTaken');
assert.equal(consoleChanges(controlled,a)[0].key,'ControlReleased');
assert.equal(consoleChanges(a,{...a,floors:[{...a.floors[0],breached:true}]})[0].key,'Breached');
assert.equal(appendConsoleEvents(Array.from({length:40},()=>({text:'old'})),changes).length,CONSOLE_LOG_LIMIT);
assert.deepEqual(data.actions.programs[0].rezzed,false,'snapshot cannot mutate gameplay state');
console.log('Console state: hidden-data filtering, confirmed state changes, bounded journal, no duplicate events, scope isolation passed');
